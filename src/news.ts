// Decorative ticker stories never spawn enemies or pickups.
export const formatFeedHeadline = (headline: string): string => {
  const text = headline.replace(/\s*;\s*/g, '. ').trim();
  return /[.!?]$/.test(text) ? text : `${text}.`;
};

export function getTickerNews(previousHeadline?: string): MarketNews {
  const pool = MEME_HEADLINES.filter(headline => headline !== previousHeadline);
  return {
    id: 'ticker-' + Math.random().toString(36).slice(2),
    headline: pool[Math.floor(Math.random() * pool.length)],
    source: TICKER_AGENCIES[Math.floor(Math.random() * TICKER_AGENCIES.length)],
    sentiment: 'diamond',
    alertBanner: '',
    durationFrames: 360,
  };
}
