export function getRandomNews(preferType?: 'bull' | 'bear' | 'diamond' | 'banknote'): MarketNews {
  let pool = SYNTHETIC_HEADLINES;
  if (preferType) {
    pool = SYNTHETIC_HEADLINES.filter((h) => h.spawnType === preferType);
  }
  const template = pool[Math.floor(Math.random() * pool.length)] || SYNTHETIC_HEADLINES[0];
  return {
    ...template,
    id: 'news-' + Math.random().toString(36).substring(2, 9)
  };
}

